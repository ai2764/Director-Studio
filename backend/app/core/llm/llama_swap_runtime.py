"""Bundled ("built-in") llama.cpp runtime: one llama-swap process owned by the backend.

``DS_LLM_PROVIDER=llama-swap`` + ``DS_LLAMA_SWAP_MODE=bundled`` starts DS's private
llama-swap (``runtime/llama-swap``, MIT) on a free loopback port.  llama-swap spawns
llama-server (``runtime/llama.cpp``, MIT; CUDA build on Windows, CPU build on Linux)
on demand, so to the user the LLM is a single service that DS starts and stops.

The llama-swap ``config.yaml`` lives in the DS data directory and is generated from
the GGUF files under the LLM models folder plus DS settings (context size, GPU layers,
MTP speculative decoding).  It is rewritten whenever settings or the model set change
and llama-swap picks it up through ``-watch-config``; a port/binary change restarts it.
Users never edit it.  In ``remote`` mode DS talks to the user's own llama-swap at
``DS_LLM_BASE_URL`` and reads the context capacity from the loaded model instead.
"""

from __future__ import annotations

import json
import logging
import os
import struct
from pathlib import Path
from typing import Any

import httpx

from ...config import settings
from ...runtime_paths import runtime_paths
from ..comfy.launch_options import child_environment
from ..process.managed import LaunchSpec, LoopLocalLock, ManagedProcess, port_is_free, reserve_loopback_port

logger = logging.getLogger("director_studio.llama_swap_runtime")

REMOTE_DEFAULT_PORT = 11435  # the documented port of a user's own llama-swap
CONFIG_HEADER = ("# Generated by Director Studio - do not edit; it is rewritten on every settings or model change.\n"
                 "# (YAML; written as JSON, which is valid YAML.)\n")


# ---- paths -----------------------------------------------------------------------------

def llama_swap_dir(cfg: Any = settings) -> Path:
    configured = str(getattr(cfg, "llama_swap_dir", "") or "").strip()
    return Path(configured).expanduser() if configured else runtime_paths.install_root / "runtime" / "llama-swap"


def llama_cpp_dir(cfg: Any = settings) -> Path:
    configured = str(getattr(cfg, "llama_cpp_dir", "") or "").strip()
    return Path(configured).expanduser() if configured else runtime_paths.install_root / "runtime" / "llama.cpp"


def _exe(name: str) -> str:
    return f"{name}.exe" if os.name == "nt" else name


def llama_swap_binary(cfg: Any = settings) -> Path | None:
    candidate = llama_swap_dir(cfg) / _exe("llama-swap")
    return candidate if candidate.is_file() else None


def llama_server_binary(cfg: Any = settings) -> Path | None:
    candidate = llama_cpp_dir(cfg) / _exe("llama-server")
    return candidate if candidate.is_file() else None


def llm_models_dir(cfg: Any = settings) -> Path:
    configured = str(getattr(cfg, "llama_models_dir", "") or "").strip()
    if configured:
        return Path(configured).expanduser()
    from ..comfy.runtime import models_dir

    return models_dir(cfg) / "llm"


def config_path(cfg: Any = settings) -> Path:
    return Path(cfg.data_dir) / "llama-swap" / "config.yaml"


def wants_bundled(cfg: Any = settings) -> bool:
    return getattr(cfg, "llama_swap_mode", "remote") == "bundled" and getattr(cfg, "llm_provider", "") == "llama-swap"


# ---- GGUF inspection -------------------------------------------------------------------

_GGUF_SCALAR = {0: 1, 1: 1, 2: 2, 3: 2, 4: 4, 5: 4, 6: 4, 7: 1, 10: 8, 11: 8, 12: 8}
_GGUF_INT = {0: "<B", 1: "<b", 2: "<H", 3: "<h", 4: "<I", 5: "<i", 7: "<?", 10: "<Q", 11: "<q"}


def gguf_metadata(path: Path, wanted_suffixes: tuple[str, ...] = ("nextn_predict_layers", "context_length",
                                                                   "general.architecture")) -> dict[str, Any]:
    """Read selected scalar/string keys from a GGUF header (no tensors, stops after the KV table)."""
    out: dict[str, Any] = {}
    with open(path, "rb") as fh:
        if fh.read(4) != b"GGUF":
            raise ValueError("not a GGUF file")
        version, = struct.unpack("<I", fh.read(4))
        if version < 2:
            raise ValueError("unsupported GGUF version")
        _n_tensors, n_kv = struct.unpack("<QQ", fh.read(16))

        def read_str() -> str:
            n, = struct.unpack("<Q", fh.read(8))
            if n > 1 << 24:
                raise ValueError("corrupt GGUF string")
            return fh.read(n).decode("utf-8", errors="replace")

        def skip_value(vtype: int) -> None:
            if vtype in _GGUF_SCALAR:
                fh.seek(_GGUF_SCALAR[vtype], 1)
            elif vtype == 8:
                n, = struct.unpack("<Q", fh.read(8))
                fh.seek(n, 1)
            elif vtype == 9:
                itype, count = struct.unpack("<IQ", fh.read(12))
                if itype in _GGUF_SCALAR:
                    fh.seek(_GGUF_SCALAR[itype] * count, 1)
                else:
                    for _ in range(count):
                        skip_value(itype)
            else:
                raise ValueError(f"unknown GGUF value type {vtype}")

        for _ in range(min(n_kv, 100_000)):
            key = read_str()
            vtype, = struct.unpack("<I", fh.read(4))
            if key.endswith(wanted_suffixes) and (vtype in _GGUF_INT or vtype == 8):
                if vtype == 8:
                    out[key] = read_str()
                else:
                    fmt = _GGUF_INT[vtype]
                    out[key], = struct.unpack(fmt, fh.read(struct.calcsize(fmt)))
            else:
                skip_value(vtype)
    return out


def gguf_has_mtp(path: Path) -> bool:
    try:
        meta = gguf_metadata(path)
    except (OSError, ValueError, struct.error):
        return False
    return any(k.endswith("nextn_predict_layers") and int(v or 0) > 0 for k, v in meta.items())


# ---- config generation -----------------------------------------------------------------

def discover_models(cfg: Any = settings) -> list[dict[str, Any]]:
    """GGUF chat models in the LLM folder (projector files and partial downloads skipped)."""
    from ..deps import catalog

    root = llm_models_dir(cfg)
    if not root.is_dir():
        return []
    known = {m["file"]: m for m in catalog.llm_models()}
    found: list[dict[str, Any]] = []
    for path in sorted(root.rglob("*.gguf")):
        name = path.name
        lower = name.lower()
        if lower.startswith("mmproj") or "-mmproj" in lower:
            continue
        if "-of-" in lower and "-00001-of-" not in lower:
            continue  # split GGUF: llama.cpp loads the rest from the first shard
        entry = known.get(name)
        meta = (entry or {}).get("llm") or {}
        model_id = (entry or {}).get("model_id") or path.stem
        mtp = bool(meta["mtp"]) if "mtp" in meta else gguf_has_mtp(path)
        found.append({"id": model_id, "path": path, "mtp": mtp,
                      "draft_n_max": int(meta.get("spec_draft_n_max", 2)),
                      "extra_args": list(meta.get("extra_args", []))})
    seen: set[str] = set()
    for item in found:  # unique ids even if two folders hold the same file name
        base, n = item["id"], 2
        while item["id"] in seen:
            item["id"], n = f"{base}-{n}", n + 1
        seen.add(item["id"])
    return found


def _q(value: str | Path) -> str:
    """Quote one argv item for llama-swap's shell-like cmd parser (forward slashes on Windows)."""
    text = str(value).replace("\\", "/") if os.name == "nt" else str(value)
    return '"' + text.replace('"', '') + '"' if any(c in text for c in ' \t"\'') else text


def model_cmd(server: Path, model: dict[str, Any], cfg: Any = settings) -> str:
    args = [_q(server), "--host", "127.0.0.1", "--port", "${PORT}", "-m", _q(model["path"]),
            "-c", str(int(cfg.director_num_ctx)), "-ngl", str(cfg.llama_gpu_layers or "auto").strip() or "auto",
            "-np", "1", "--jinja", "--no-webui"]
    if model["mtp"] and cfg.llama_mtp:
        args += ["--spec-type", "draft-mtp", "--spec-draft-n-max", str(model["draft_n_max"])]
    args += [_q(a) for a in model["extra_args"]]
    return " ".join(args)


def render_config(cfg: Any = settings, server: Path | None = None) -> str:
    server = server or llama_server_binary(cfg) or (llama_cpp_dir(cfg) / _exe("llama-server"))
    models = {}
    for model in discover_models(cfg):
        models[model["id"]] = {
            "cmd": model_cmd(server, model, cfg),
            "ttl": 0,  # DS's VRAM orchestrator unloads explicitly (/api/models/unload)
            "metadata": {"ds_path": str(model["path"]), "ds_mtp": bool(model["mtp"] and cfg.llama_mtp)},
        }
    doc = {"healthCheckTimeout": 900, "logLevel": "info", "startPort": 15800, "models": models}
    return CONFIG_HEADER + json.dumps(doc, indent=2, ensure_ascii=False) + "\n"


def write_config(cfg: Any = settings) -> tuple[Path, bool]:
    """Write config.yaml atomically; returns (path, changed)."""
    path = config_path(cfg)
    text = render_config(cfg)
    path.parent.mkdir(parents=True, exist_ok=True)
    try:
        if path.read_text(encoding="utf-8") == text:
            return path, False
    except FileNotFoundError:
        pass
    tmp = path.with_name(path.name + ".tmp")
    tmp.write_text(text, encoding="utf-8")
    os.replace(tmp, path)
    return path, True


async def _health(url: str) -> bool:
    try:
        async with httpx.AsyncClient(timeout=3.0, trust_env=False) as client:
            return (await client.get(f"{url}/v1/models")).status_code == 200
    except httpx.HTTPError:
        return False


# ---- runtime ---------------------------------------------------------------------------

class LlamaSwapRuntime:
    def __init__(self) -> None:
        self.managed: ManagedProcess | None = None
        self.error: str | None = None
        self.effective_url: str | None = None  # http://127.0.0.1:<port>/v1 while bundled
        self._port = 0
        self._lock = LoopLocalLock()
        self._signature: tuple[str, ...] = ()

    @property
    def bundled(self) -> bool:
        return self.managed is not None

    def base_url(self) -> str | None:
        """OpenAI-compatible base URL of the bundled llama-swap (None when not bundled)."""
        return self.effective_url if self.managed is not None else None

    def _build(self) -> LaunchSpec:
        binary = llama_swap_binary()
        if binary is None:
            raise FileNotFoundError(f"bundled llama-swap not found under {llama_swap_dir()}")
        if not self._port or (not settings.llama_swap_port and not port_is_free(self._port)):
            port = settings.llama_swap_port or reserve_loopback_port()
            while not settings.llama_swap_port and port == REMOTE_DEFAULT_PORT:
                port = reserve_loopback_port()
            self._port = port
        path, _ = write_config()
        env = child_environment({})
        for key in [k for k in env if k.startswith("LLAMA_ARG_")]:
            env.pop(key)  # a user's LLAMA_ARG_* must not change the private llama-server
        server_dir = llama_cpp_dir()
        if os.name != "nt":
            env["LD_LIBRARY_PATH"] = os.pathsep.join(p for p in (str(server_dir), env.get("LD_LIBRARY_PATH", "")) if p)
        else:
            env["PATH"] = os.pathsep.join((str(server_dir), env.get("PATH", "")))
        origin = f"http://127.0.0.1:{self._port}"
        self.effective_url = origin + "/v1"
        argv = [str(binary), "-config", str(path), "-listen", f"127.0.0.1:{self._port}", "-watch-config"]
        return LaunchSpec(argv=argv, cwd=path.parent, env=env, health=lambda: _health(origin),
                          startup_timeout=60.0, label=f"{binary} ({origin}, config {path})")

    async def start(self) -> None:
        async with self._lock:
            await self._start_locked()

    async def _start_locked(self) -> None:
        self.error = None
        if not wants_bundled():
            return
        if llama_swap_binary() is None:
            self.error = f"bundled llama-swap not found under {llama_swap_dir()}"
            logger.error(self.error)
            return
        if llama_server_binary() is None:
            self.error = f"bundled llama-server not found under {llama_cpp_dir()}"
            logger.error(self.error)
        self._signature = _signature()
        self.managed = ManagedProcess(
            name="llama-swap", build=self._build,
            log_path=Path(settings.data_dir) / "logs" / "llama-swap.log",
            pid_file=Path(settings.data_dir) / "run" / "llama-swap.pid",
        )
        await self.managed.start()
        if not await self.managed.wait_ready(60):
            self.error = self.managed.last_error
        _rebuild_llm_clients()

    async def stop(self) -> None:
        async with self._lock:
            await self._stop_locked()

    async def _stop_locked(self) -> None:
        if self.managed is not None:
            await self.managed.stop()
            self.managed = None
        self._port = 0
        self.effective_url = None

    def refresh_config(self) -> bool:
        """Regenerate config.yaml (models/settings changed); llama-swap hot-reloads it."""
        if not wants_bundled():
            return False
        try:
            return write_config()[1]
        except OSError as exc:
            logger.warning("llama-swap config not written: %s", exc)
            return False

    async def reconfigure(self) -> str:
        """Re-apply after LLM settings changed: rewrite the config, restart only if needed."""
        async with self._lock:
            want = wants_bundled()
            if (want and self.managed is not None and self.managed.state in {"ready", "starting"}
                    and self._signature == _signature()):
                self.refresh_config()  # ctx / GPU layers / MTP: hot reload via -watch-config
                return "reloaded"
            await self._stop_locked()
            await self._start_locked()
            if not want:
                _rebuild_llm_clients()
        return "bundled" if want else "remote"

    def status(self) -> dict[str, Any]:
        data: dict[str, Any] = {
            "mode": settings.llama_swap_mode,
            "bundled_active": self.managed is not None,
            "effective_url": self.base_url(),
            "binary": str(llama_swap_binary() or ""),
            "server_binary": str(llama_server_binary() or ""),
            "available": llama_swap_binary() is not None and llama_server_binary() is not None,
            "models_dir": str(llm_models_dir()),
            "config_path": str(config_path(settings)),
            "models": [m["id"] for m in discover_models()] if wants_bundled() else [],
            "error": self.error,
        }
        if self.managed is not None:
            data["managed"] = self.managed.status()
        return data


def _signature() -> tuple[str, ...]:
    return (str(llama_swap_binary()), str(llama_server_binary()), str(settings.llama_swap_port),
            str(settings.data_dir))


def _rebuild_llm_clients() -> None:
    try:
        from ..config_store.service import rebuild_llm

        rebuild_llm()
    except Exception:  # noqa: BLE001 - best effort during startup/tests
        logger.debug("LLM client rebuild skipped", exc_info=True)


llama_swap_runtime = LlamaSwapRuntime()
