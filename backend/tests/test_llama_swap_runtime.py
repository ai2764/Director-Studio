def test_runtime_starts_one_llama_swap_and_hot_reloads(fake_swap, llm_dir, monkeypatch):
    async def scenario():
        _gguf(llm_dir / "A.gguf", {})
        await fake_swap.start()
        assert fake_swap.error is None and fake_swap.bundled
        url = fake_swap.base_url()
        assert url.startswith("http://127.0.0.1:") and url.endswith("/v1") and ":11435/" not in url
        async with httpx.AsyncClient(trust_env=False) as client:
            assert [m["id"] for m in (await client.get(url + "/models")).json()["data"]] == ["A"]
            pid = fake_swap.managed.pid
            # new model + ctx change -> config rewritten, same process (hot reload)
            _gguf(llm_dir / "B.gguf", {})
            monkeypatch.setattr(settings, "director_num_ctx", 12288)
            assert await fake_swap.reconfigure() == "reloaded"
            assert fake_swap.managed.pid == pid
            assert "-c 12288" in rt.config_path().read_text()
            assert {m["id"] for m in (await client.get(url + "/models")).json()["data"]} == {"A", "B"}
            # port change -> restart
            monkeypatch.setattr(settings, "llama_swap_port", rt.reserve_loopback_port())
            assert await fake_swap.reconfigure() == "bundled"
            assert fake_swap.base_url() == f"http://127.0.0.1:{settings.llama_swap_port}/v1"
            # remote mode -> stopped
            monkeypatch.setattr(settings, "llama_swap_mode", "remote")
            assert await fake_swap.reconfigure() == "remote"
            assert not fake_swap.bundled and fake_swap.base_url() is None

    asyncio.run(scenario())


