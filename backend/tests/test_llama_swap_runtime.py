def test_installer_manifest_pins_llama_cpp_and_llama_swap():
    manifest = json.loads((REPO / "installer" / "manifest.json").read_text())
    assert "ollama" not in manifest
    lcpp, swap = manifest["llama_cpp"], manifest["llama_swap"]
    assert lcpp["license"] == swap["license"] == "MIT"
    assert set(lcpp["windows-x64"]["variants"]) == {"cpu", "cu128", "cu130"}
    assert "cuda" in lcpp["windows-x64"]["variants"]["cu128"]["url"]
    assert "ubuntu-x64" in lcpp["linux-x86_64"]["variants"]["*"]["url"]  # CPU build on Linux
    for spec in [*lcpp["windows-x64"]["variants"].values(), lcpp["linux-x86_64"]["variants"]["*"],
                 swap["windows-x64"], swap["linux-x86_64"]]:
        assert len(spec["sha256"]) == 64 and lcpp["version"] in spec["url"] or swap["version"] in spec["url"]
        for extra in spec.get("extras", []):
            assert len(extra["sha256"]) == 64


@pytest.mark.skipif(not os.environ.get("DS_LLAMA_SMOKE_GGUF"), reason="set DS_LLAMA_SMOKE_GGUF + _SWAP_DIR + _CPP_DIR")
def test_real_llama_swap_cpu_smoke(llm_dir, monkeypatch):
    """End-to-end with real binaries and a tiny GGUF (CPU): chat, capacity, unload, hot reload."""
    from app.core.llm import factory

    gguf = Path(os.environ["DS_LLAMA_SMOKE_GGUF"])
    llm_dir.mkdir(parents=True)
    os.symlink(gguf, llm_dir / gguf.name)
    monkeypatch.setattr(settings, "llama_swap_dir", os.environ["DS_LLAMA_SMOKE_SWAP_DIR"])
    monkeypatch.setattr(settings, "llama_cpp_dir", os.environ["DS_LLAMA_SMOKE_CPP_DIR"])
    monkeypatch.setattr(settings, "llama_gpu_layers", "0")
    monkeypatch.setattr(settings, "director_num_ctx", 4096)
    monkeypatch.setattr(settings, "llm_api_key", None)
    monkeypatch.setattr(settings, "llm_extra_headers", "")
    monkeypatch.setattr(rt, "_rebuild_llm_clients", lambda: None)
    runtime = rt.llama_swap_runtime
    model = gguf.stem

    async def scenario():
        await runtime.start()
        try:
            assert runtime.error is None, runtime.error
            factory.reset_llm_provider()
            provider = factory.get_llm_provider()
            assert model in await provider.list_models()
            await provider.lifecycle.prepare(model)
            assert await provider.lifecycle.context_capacity(model) == 4096
            text = await provider.client.chat(model, "Reply with the single word PONG. /no_think",
                                              options={"num_predict": 40})
            assert "PONG" in text.upper()
            await provider.lifecycle.release([model])
            assert not (await provider.lifecycle.status(model))["ready"]
            monkeypatch.setattr(settings, "director_num_ctx", 8192)
            assert await runtime.reconfigure() == "reloaded"
            await asyncio.sleep(1.5)
            await provider.lifecycle.prepare(model)
            assert await provider.lifecycle.context_capacity(model) == 8192
            await provider.lifecycle.release([model])
        finally:
            await runtime.stop()
            factory.reset_llm_provider()

    asyncio.run(scenario())


