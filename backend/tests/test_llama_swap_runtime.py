def _gguf(path: Path, kv: dict[str, object]) -> Path:
    def s(text: str) -> bytes:
        raw = text.encode()
        return struct.pack("<Q", len(raw)) + raw

    body = b"GGUF" + struct.pack("<IQQ", 3, 0, len(kv) + 1)
    # an array value first, to exercise skipping
    body += s("tokenizer.ggml.tokens") + struct.pack("<IIQ", 9, 8, 2) + s("a") + s("bc")
    for key, value in kv.items():
        if isinstance(value, str):
            body += s(key) + struct.pack("<I", 8) + s(value)
        else:
            body += s(key) + struct.pack("<II", 4, int(value))
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_bytes(body + b"\0" * 64)
    return path


