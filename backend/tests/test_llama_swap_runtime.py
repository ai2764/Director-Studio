def _doc(text: str) -> dict:
    assert text.startswith("# Generated by Director Studio")
    return json.loads("\n".join(line for line in text.splitlines() if not line.startswith("#")))


def test_gguf_metadata_and_mtp_detection(tmp_path):
    plain = _gguf(tmp_path / "a.gguf", {"general.architecture": "qwen3", "qwen3.context_length": 40960})
    mtp = _gguf(tmp_path / "b.gguf", {"general.architecture": "qwen35", "qwen35.nextn_predict_layers": 1})
    meta = rt.gguf_metadata(plain)
    assert meta["general.architecture"] == "qwen3" and meta["qwen3.context_length"] == 40960
    assert not rt.gguf_has_mtp(plain) and rt.gguf_has_mtp(mtp)
    (tmp_path / "bad.gguf").write_bytes(b"nope")
    assert not rt.gguf_has_mtp(tmp_path / "bad.gguf")


def test_render_config_from_models_and_settings(llm_dir, monkeypatch):
    _gguf(llm_dir / "Plain-Q4.gguf", {"general.architecture": "qwen3"})
    _gguf(llm_dir / "Fast-MTP.gguf", {"qwen35.nextn_predict_layers": 1})
    _gguf(llm_dir / "mmproj-F16.gguf", {})
    _gguf(llm_dir / "Big-00002-of-00002.gguf", {})
    _gguf(llm_dir / "Big-00001-of-00002.gguf", {})
    (llm_dir / "Half.gguf.part").write_bytes(b"x")
    known = catalog.llm_models()[0]
    _gguf(llm_dir / known["file"], {})
    doc = _doc(rt.render_config())
    models = doc["models"]
    assert set(models) == {"Plain-Q4", "Fast-MTP", "Big-00001-of-00002", known["model_id"]}
    plain, fast = models["Plain-Q4"]["cmd"], models["Fast-MTP"]["cmd"]
    for cmd in (plain, fast):
        assert "--port ${PORT}" in cmd and "--host 127.0.0.1" in cmd
        assert "-c 32768" in cmd and "-ngl auto" in cmd and "-np 1" in cmd
    assert "--spec-type draft-mtp --spec-draft-n-max 2" in fast and "--spec-type" not in plain
    assert models["Plain-Q4"]["ttl"] == 0  # DS's orchestrator unloads explicitly

    monkeypatch.setattr(settings, "director_num_ctx", 8192)
    monkeypatch.setattr(settings, "llama_gpu_layers", "0")
    monkeypatch.setattr(settings, "llama_mtp", False)
    fast = _doc(rt.render_config())["models"]["Fast-MTP"]["cmd"]
    assert "-c 8192" in fast and "-ngl 0" in fast and "--spec-type" not in fast


