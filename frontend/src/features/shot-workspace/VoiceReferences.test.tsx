// @vitest-environment jsdom
import {cleanup,fireEvent,render,screen,waitFor} from "@testing-library/react";
import {afterEach,expect,it,vi} from "vitest";
import {VoiceReferences} from "./VoiceReferences";
import type {Shot} from "../../shared/api/types";
import {listLibraryAssets} from "../library/api";
import {LIBRARY_CHANGED} from "../library/libraryChanges";
vi.mock("../library/api",()=>({listLibraryAssets:vi.fn()}));
vi.mock("../library/AssetImportDialog",()=>({AssetImportDialog:()=>null}));
afterEach(()=>{cleanup();vi.unstubAllGlobals();vi.clearAllMocks();});
it("finds newly imported voices when returning to an already open selector",async()=>{
  const shot={id:"shot_test",project_id:"project_test",voice_refs:[],source_audio_path:null} as unknown as Shot;
  vi.mocked(listLibraryAssets).mockResolvedValue([]);
  render(<VoiceReferences shot={shot} disabled={false} onSaved={vi.fn()}/>);
  const details=screen.getByText("Voice references · 0 / 3").closest("details")!;
  details.open=true;fireEvent(details,new Event("toggle"));
  await screen.findByText("No voice samples yet. Import one below.");
  vi.mocked(listLibraryAssets).mockResolvedValue([{id:"voice_new",name:"New voice",meta:{h3_ready:true},urls:{reference:"/new.wav"}} as never]);
  fireEvent(window,new Event("focus"));
  await screen.findByRole("option",{name:"New voice"});
  fireEvent(window,new Event(LIBRARY_CHANGED));
  await waitFor(()=>expect(listLibraryAssets).toHaveBeenCalledTimes(3));
});
it("links and removes a voice immediately without a save button",async()=>{
  const shot = {id:"shot_test",project_id:"project_test",voice_refs:[],source_audio_path:null} as unknown as Shot;
  vi.mocked(listLibraryAssets).mockResolvedValue([{id:"voice_one",name:"Guide",meta:{h3_ready:true},urls:{reference:"/test-reference.wav"}} as never]);
  const fetcher=vi.fn(async()=>({ok:true,json:async()=>({...shot,voice_refs:[{asset_id:"voice_one",audio_index:1,file_key:"reference",speaker:"Guide",notes:""}]})}));
  vi.stubGlobal("fetch",fetcher);const onSaved=vi.fn();
  render(<VoiceReferences shot={shot} disabled={false} onSaved={onSaved}/>);
  const details=screen.getByText("Voice references · 0 / 3").closest("details")!;
  details.open=true;fireEvent(details,new Event("toggle"));
  await screen.findByRole("option",{name:"Guide"});
  expect(listLibraryAssets).toHaveBeenCalledWith("voices","project_test");
  fireEvent.change(screen.getByLabelText("Add voice reference"),{target:{value:"voice_one"}});
  expect(screen.getByLabelText("Preview voice 1").getAttribute("src")).toBe("/test-reference.wav");
  expect(screen.queryByRole("button",{name:"Save voices"})).toBeNull();
  await waitFor(()=>expect(onSaved).toHaveBeenCalled());
  const options=fetcher.mock.calls[0] as unknown as [string,RequestInit];
  expect(options[0]).toBe("/api/shot-workspace/shots/shot_test/voice-references");
  expect(JSON.parse(options[1].body as string)).toEqual({voice_refs:[{asset_id:"voice_one",audio_index:1,file_key:"reference",speaker:"",notes:""}],expected_refs:[]});
  fireEvent.click(screen.getByRole("button",{name:"Remove voice 1"}));
  await waitFor(()=>expect(fetcher).toHaveBeenCalledTimes(2));
  const removal=fetcher.mock.calls[1] as unknown as [string,RequestInit];
  expect(JSON.parse(removal[1].body as string).voice_refs).toEqual([]);
  expect(JSON.parse(removal[1].body as string).expected_refs[0].asset_id).toBe("voice_one");
});

it("rolls back a voice selection when immediate linking fails",async()=>{
  const shot = {id:"shot_test",project_id:"project_test",voice_refs:[],source_audio_path:null} as unknown as Shot;
  vi.mocked(listLibraryAssets).mockResolvedValue([{id:"voice_one",name:"Guide",meta:{h3_ready:true},urls:{reference:"/test-reference.wav"}} as never]);
  vi.stubGlobal("fetch",vi.fn(async()=>({ok:false,json:async()=>({detail:"Voice reference total duration must not exceed 15 seconds"})})));
  const onSaved=vi.fn();render(<VoiceReferences shot={shot} disabled={false} onSaved={onSaved}/>);
  const details=screen.getByText("Voice references · 0 / 3").closest("details")!;
  details.open=true;fireEvent(details,new Event("toggle"));
  await screen.findByRole("option",{name:"Guide"});
  fireEvent.change(screen.getByLabelText("Add voice reference"),{target:{value:"voice_one"}});
  await screen.findByRole("alert");
  expect(screen.queryByLabelText("Preview voice 1")).toBeNull();
  expect(onSaved).not.toHaveBeenCalled();
});
